"""Conservative engraving-only cleanup around DuET's unchanged writer.

Work on musical events before XML, so rests/beams/stems are regenerated by
the upstream writer. A separately audited rule may restore a model note-end
after a minority late release; pitch, attacks and performance MIDI stay intact.
"""
from contextlib import contextmanager
from fractions import Fraction as F
from collections import Counter
from pathlib import Path
from copy import deepcopy
from io import BytesIO
import xml.etree.ElementTree as ET


_SHORTEST_VENDOR_TYPE = F(1, 16)
_TUPLET_WRITTEN_FACTOR = F(3, 2)
_SHORT_WRITTEN_TYPES = {}
for _denominator, _name in ((32, '128th'), (64, '256th'), (128, '512th'), (256, '1024th')):
    _base = F(1, _denominator)
    _SHORT_WRITTEN_TYPES[_base] = (_name, 0)
    _SHORT_WRITTEN_TYPES[_base * _TUPLET_WRITTEN_FACTOR] = (_name, 1)


def supported_model_release(group, *, new_attack, tail_attack):
    """Prefer a unanimous long model value over a minority late key release.

    Called only at a real bar boundary, after native voice cleanup. This is a
    notation decision, not an edit to recorded key-off or CC64 events.
    """
    if len(group) < 2 or not new_attack or tail_attack:
        return None
    duration = F(group[0]['qd'])
    if duration < 2 or any(F(n['qd']) != duration for n in group):
        return None
    extension = max(F(n['dur']) for n in group) - duration
    if not 0 < extension <= min(F(1, 2), duration / 8):
        return None
    end = float(group[0]['on'] + duration)
    held = sum(float(n['xo']) > end + .12 for n in group)
    released = any(float(n['xo']) <= end for n in group)
    if held > len(group) / 2 or not released:
        return None
    return duration


def _sounding_pitch(pitch):
    """Canonical spelling of exact pitch, retaining the public five-field key.

    A-sharp and B-flat (including octave-crossing B-sharp/C-flat) sound alike.
    Fractional alterations remain exact; MIDI conversion may reject them later.
    """
    base={'C':0,'D':2,'E':4,'F':5,'G':7,'A':9,'B':11}[pitch.findtext('step')]
    value=F((int(pitch.findtext('octave'))+1)*12+base)+F(pitch.findtext('alter','0'))
    whole=value//1
    step,alter=(('C',0),('C',1),('D',0),('D',1),('E',0),('F',0),
                ('F',1),('G',0),('G',1),('A',0),('A',1),('B',0))[whole%12]
    return step,str(F(alter)+value-whole),str(whole//12-1)


def sounding_signature(path):
    """Exact sounding intervals, independent of voice numbers and tied spelling."""
    return _sounding_signature(ET.parse(path).getroot())


def clip_boundary_ties(root):
    """Remove the missing continuation ends from a contiguous score excerpt."""
    _sounding_signature(root, clip=True)


def _remove_tie(note, kind):
    for tie in note.findall(f"tie[@type='{kind}']"):
        note.remove(tie)
    for notation in note.findall('notations'):
        for tied in notation.findall(f"tied[@type='{kind}']"):
            notation.remove(tied)


def _sounding_signature(root, *, clip=False):
    result = []
    for part in root.findall('.//part'):
        origin, divisions, active, active_voice = F(0), 1, {}, {}
        active_notes = {} if clip else None
        for measure in part.findall('measure'):
            cursor = maximum = previous = F(0)
            for child in measure:
                if child.tag == 'attributes':
                    divisions = int(child.findtext('divisions', str(divisions)))
                elif child.tag in ('backup', 'forward'):
                    cursor += F(int(child.findtext('duration')), divisions) * (-1 if child.tag == 'backup' else 1)
                elif child.tag == 'note':
                    duration = F(int(child.findtext('duration', '0')), divisions)
                    if duration <= 0 and child.find('grace') is None:
                        raise ValueError(f'Nonpositive note duration in notation: measure {measure.get("number")}')
                    onset = previous if child.find('chord') is not None else cursor
                    if child.find('chord') is None:
                        previous = cursor
                        cursor += duration
                    maximum = max(maximum, onset + duration, cursor)
                    pitch = child.find('pitch')
                    if pitch is None:
                        continue
                    key = (part.get('id'), child.findtext('staff', '1'), *_sounding_pitch(pitch))
                    start, end = origin + onset, origin + onset + duration
                    ties = {tie.get('type') for tie in child.findall('tie')}
                    matches = [i for i in active.get(key, []) if result[i][2] == start] if 'stop' in ties else []
                    if 'stop' in ties and not matches:
                        if not clip:
                            raise ValueError(f'Unmatched tie in notation: measure {measure.get("number")}, '
                                             f'pitch {key[2:]}, beat {start}')
                        _remove_tie(child, 'stop')
                        ties.remove('stop')
                    if 'stop' in ties:
                        # Voice labels may change across bars, as in native
                        # DuET hand layout. A unique contiguous sounding pitch
                        # is safe; simultaneous unisons need voice disambiguation.
                        same_voice=[i for i in matches if active_voice.get(i)==child.findtext('voice','1')]
                        candidates=same_voice if same_voice else matches
                        if len(candidates)!=1:
                            raise ValueError('Ambiguous tied unison in notation')
                        index = candidates[0]
                        active[key].remove(index)
                        if clip:
                            active_notes.pop(index)
                        result[index] = (key, result[index][1], end, False)
                    else:
                        index = len(result)
                        result.append((key, start, end, child.find('grace') is not None))
                    if 'start' in ties:
                        active.setdefault(key, []).append(index)
                        active_voice[index]=child.findtext('voice','1')
                        if clip:
                            active_notes[index] = child
            origin += maximum
        if clip:
            for note in active_notes.values():
                _remove_tie(note, 'start')
        elif any(active.values()):
            raise ValueError('Dangling tie in notation')
    return Counter(result)


def normalize_tied_spelling(path):
    """Keep the attack's spelling through an explicit, contiguous tie chain.

    No unmarked reattack is joined. Exact sounding pitch and time must already
    pass signature validation. An explicit accidental explains the retained
    spelling even across a key change; unknown microtonal glyphs are diagnosed.
    """
    before=sounding_signature(path)
    tree=ET.parse(path);changes=[];skipped=[]
    accidentals={F(-2):'flat-flat',F(-1):'flat',F(0):'natural',F(1):'sharp',F(2):'double-sharp',
                 F(-1,2):'quarter-flat',F(1,2):'quarter-sharp',
                 F(-3,2):'three-quarters-flat',F(3,2):'three-quarters-sharp'}
    def spelling(pitch):return tuple(pitch.findtext(k,'0') for k in ('step','alter','octave'))
    for part in tree.findall('.//part'):
        origin=F(0);divisions=1;active={}
        for measure in part.findall('measure'):
            cursor=previous=maximum=F(0)
            for child in measure:
                if child.tag=='attributes':divisions=int(child.findtext('divisions',str(divisions)))
                elif child.tag in ('backup','forward'):
                    cursor+=F(int(child.findtext('duration')),divisions)*(-1 if child.tag=='backup' else 1)
                elif child.tag=='note':
                    duration=F(int(child.findtext('duration','0')),divisions)
                    onset=previous if child.find('chord') is not None else cursor
                    if child.find('chord') is None:previous=cursor;cursor+=duration
                    maximum=max(maximum,onset+duration,cursor)
                    pitch=child.find('pitch')
                    if pitch is None:continue
                    start=origin+onset;end=start+duration;voice=child.findtext('voice','1')
                    key=(child.findtext('staff','1'),*_sounding_pitch(pitch))
                    ties={tie.get('type') for tie in child.findall('tie')}
                    if 'stop' in ties:
                        matches=[item for item in active.get(key,[]) if item['end']==start]
                        same_voice=[item for item in matches if item['voice']==voice]
                        candidates=same_voice if same_voice else matches
                        if len(candidates)!=1:raise ValueError('Tie chain changed during spelling normalization')
                        item=candidates[0];active[key].remove(item)
                        original=item['pitch']
                        if spelling(pitch)!=spelling(original):
                            detail={'measure':measure.get('number'),'staff':key[0],'voice':voice,
                                    'beat':float(start),'from':spelling(pitch),'to':spelling(original)}
                            glyph=accidentals.get(F(original.findtext('alter','0')))
                            if glyph is None:skipped.append(dict(detail,reason='unsupported_accidental_glyph'))
                            else:
                                index=list(child).index(pitch);child.remove(pitch);child.insert(index,deepcopy(original))
                                accidental=child.find('accidental')
                                if accidental is None:
                                    accidental=ET.Element('accidental')
                                    following={'time-modification','stem','notehead','notehead-text','staff','beam','notations','lyric','play','listen'}
                                    index=next((i for i,x in enumerate(child) if x.tag in following),len(child))
                                    child.insert(index,accidental)
                                accidental.text=glyph;changes.append(detail)
                        item=dict(item,end=end,voice=voice)
                    else:item={'pitch':deepcopy(pitch),'end':end,'voice':voice}
                    if 'start' in ties:active.setdefault(key,[]).append(item)
            origin+=maximum
    if changes:
        encoded=ET.tostring(tree.getroot(),encoding='utf-8')
        if sounding_signature(BytesIO(encoded))!=before:
            raise ValueError('Tie spelling normalization changed sounding events')
        tree.write(path,encoding='utf-8',xml_declaration=True)
    return {'tie_spelling_corrections':len(changes),'tie_spelling_changes':changes,
            'tie_spelling_unresolved':skipped}


def simplify_release_rests(path):
    """A carry-over-only voice may end without printing filling rests over holds.

    Keep the actual tied note tail, and any real silence. Never apply this to a
    voice with a new attack in the bar. Short tails are review items, not chopped.
    """
    tree = ET.parse(path)
    hidden, tails = 0, []
    divisions = 1
    for measure in tree.findall('.//measure'):
        cursor = previous = F(0)
        voices = {}
        for child in measure:
            if child.tag == 'attributes':
                divisions = int(child.findtext('divisions', str(divisions)))
            elif child.tag in ('backup', 'forward'):
                cursor += F(int(child.findtext('duration')), divisions) * (-1 if child.tag == 'backup' else 1)
            elif child.tag == 'note':
                duration = F(int(child.findtext('duration', '0')), divisions)
                start = previous if child.find('chord') is not None else cursor
                if child.find('chord') is None:
                    previous = cursor
                    cursor += duration
                key = (child.findtext('staff', '1'), child.findtext('voice', '1'))
                voices.setdefault(key, []).append((start, start + duration, child))
        for (staff, voice), events in voices.items():
            pitched = [(s, e, n) for s, e, n in events if n.find('pitch') is not None]
            if not pitched or any(n.find("tie[@type='stop']") is None for _, _, n in pitched):
                continue
            last_end = max(e for _, e, _ in pitched)
            if last_end <= F(1, 2):
                tails.append({'measure': measure.get('number'), 'staff': staff,
                              'voice': voice, 'end_beat_in_bar': float(last_end),
                              'action': 'retain_duration_review_release'})
            cover = sorted((s, e) for (st, v), seq in voices.items() if st == staff and v != voice
                           for s, e, n in seq if n.find('pitch') is not None)
            for start, end, note in events:
                if note.find('rest') is None or start < last_end or note.get('print-object') == 'no':
                    continue
                filled = start
                for s, e in cover:
                    if s <= filled < e:
                        filled = e
                if filled >= end:
                    note.set('print-object', 'no')
                    hidden += 1
    tree.write(path, encoding='utf-8', xml_declaration=True)
    return {'release_voice_rests_hidden': hidden, 'short_barline_tails': tails}


def sequential_items(a, b):
    """Collapse only when all chord events are sequential, never truncate holds."""
    items = sorted(a + b, key=lambda item: item[0])
    return items if all(x[1] <= y[0] for x, y in zip(items, items[1:])) else None


def compactable_bars(streams):
    """Preserve the printed voice of every tie crossing a retained two-voice bar.

    streams is a list of (A items, B items). The writer orders voices by mean
    pitch. Reject candidates iteratively: removing one may constrain a neighbour.
    """
    candidates = {i for i, (a, b) in enumerate(streams)
                  if b and sequential_items(a, b) is not None}
    def printed_voice(items, event):
        a, b = items
        mean = lambda seq: sum(n['pitch'] for _, _, p in seq for n in p['ev']['notes']) / max(1, sum(len(p['ev']['notes']) for _, _, p in seq))
        order = (b, a) if b and mean(b) > mean(a) else (a, b)
        return next((v for v, seq in enumerate(order)
                     if any(p['ev'] is event for _, _, p in seq)), None)
    changed = True
    while changed:
        changed = False
        for i in sorted(candidates):
            bad = False
            for _, _, payload in streams[i][0] + streams[i][1]:
                for flag, neighbour in (('tie_in', i - 1), ('tie_out', i + 1)):
                    if payload[flag] and 0 <= neighbour < len(streams) and neighbour not in candidates:
                        if printed_voice(streams[neighbour], payload['ev']) == 1:
                            bad = True
            if bad:
                candidates.remove(i)
                changed = True
    return candidates


def dotted_allowed(start, duration, bar, compound=False):
    """Concise dotted notes, while keeping offbeat metric boundaries legible."""
    if compound or start + duration > bar:
        return False  # upstream already handles compound grouping
    if duration == 3:
        return start == 0
    if duration == F(3, 2):
        # Simple 3/4 can show the second half of a dotted-quarter pair as one
        # value. The 2-quarter midpoint below belongs to 4/4, not every meter.
        if bar == 3 and start == F(3, 2):
            return True
        # On-beat dotted quarters, or an offbeat ending at the half-bar boundary.
        return start.denominator == 1 or (
            start % 1 == F(1, 2) and int(start / 2) == int((start + duration - F(1, 1000)) / 2))
    if duration in (F(3, 4), F(3, 8)):
        unit = F(1) if duration == F(3, 4) else F(1, 2)
        return start % unit + duration <= unit
    return False


def compact_dotted(pieces, bar, *, compound=False, cuts=()):
    """Merge only pieces of the SAME event, with no tuplet or explicit cut."""
    result, count, i = [], 0, 0
    while i < len(pieces):
        first = pieces[i]
        end, chosen = first['s'] + first['d'], i
        if first['pl'] is not None and first['reg'] is None:
            j = i + 1
            while j < len(pieces):
                following = pieces[j]
                if following['pl'] is not first['pl'] or following['reg'] is not None or following['s'] != end:
                    break
                end += following['d']
                if any(first['s'] < c < end for c in cuts):
                    break
                if dotted_allowed(first['s'], end - first['s'], F(bar), compound):
                    chosen = j
                j += 1
        merged = dict(first)
        if chosen > i:
            merged['d'] = pieces[chosen]['s'] + pieces[chosen]['d'] - first['s']
            count += chosen - i
        result.append(merged)
        i = chosen + 1
    for i, piece in enumerate(result):
        piece['cont_prev'] = i > 0 and piece['pl'] is not None and result[i - 1]['pl'] is piece['pl']
        piece['cont_next'] = i + 1 < len(result) and piece['pl'] is not None and result[i + 1]['pl'] is piece['pl']
    return result, count


@contextmanager
def readable_writer(upstream):
    """Scoped in the isolated notation worker; keep the pinned vendor untouched."""
    from duet.readable import musicxml
    original_write = upstream.write
    original_assign = upstream.assign
    original_items = musicxml.bar_items
    original_layout = musicxml.layout_voice
    original_type = musicxml.type_of
    audit = {'collapsed_staff_bars': [], 'tie_fragments_removed': 0, 'model_release_restored': []}

    def type_of(value, tuplet):
        # The vendor table stops at 64th. A mixed binary/triplet boundary
        # can leave a 1/48-quarter fragment that needs a 128th at 3:2.
        # MuseScore uses the written type to lay out the tuplet, so its
        # duration must agree with the writer's already-exact tick count.
        if value < _SHORTEST_VENDOR_TYPE:
            written = value * _TUPLET_WRITTEN_FACTOR if tuplet else value
            exact = _SHORT_WRITTEN_TYPES.get(written)
            if exact is not None:
                return exact
        return original_type(value, tuplet)

    def assign(notes, staff, ctx):
        from bisect import bisect_left
        before = {id(n): n['dur'] for n in notes if n['staff'] == staff and not n['grace']}
        pool = original_assign(notes, staff, ctx)
        non_grace_onsets = {n['on'] for n in notes if not n['grace']}
        groups = {}
        layer_onsets = {}
        for n in pool:
            layer = n['layer']
            groups.setdefault((layer, n['on']), []).append(n)
            layer_onsets.setdefault(layer, []).append(n['on'])
        for on_list in layer_onsets.values():
            on_list.sort()
        for (layer, onset), group in groups.items():
            if any(before.get(id(n)) != n['qd'] for n in group):
                continue  # preserve earlier rhythm/phrase cleanup
            boundary = onset + group[0]['qd']
            bar = ctx.bar_of(onset)
            if boundary != ctx.bars.end(bar):
                continue
            new_attack = boundary in non_grace_onsets
            end = max(n['on'] + n['dur'] for n in group)
            on_list = layer_onsets[layer]
            pos = bisect_left(on_list, boundary)
            tail_attack = pos < len(on_list) and on_list[pos] < end
            duration = supported_model_release(group, new_attack=new_attack, tail_attack=tail_attack)
            if duration is None:
                continue
            audit['model_release_restored'].append({'staff': staff + 1,
                'boundary_beat': float(boundary), 'input_ids': [n.get('i') for n in group],
                'pitches': [n['pitch'] for n in group], 'before_duration': float(end - onset),
                'model_duration': float(duration), 'reason': 'model_bar_end_with_majority_release_and_new_attack'})
            for n in group:
                n['dur'] = duration
        return pool

    def layout(items, B, cut=None, compound=False, extra_cuts=()):
        pieces = original_layout(items, B, cut=cut, compound=compound, extra_cuts=extra_cuts)
        pieces, count = compact_dotted(pieces, B, compound=compound,
                                      cuts=tuple(extra_cuts) + ((cut,) if cut else ()))
        audit['tie_fragments_removed'] += count
        return pieces

    def write(plan, ctx, path):
        from bisect import bisect_left, bisect_right
        from .notation_precision import engraving_divisions
        plan.divisions = engraving_divisions(plan, ctx)
        audit['divisions'] = plan.divisions
        # Pre-index each event stream into bars in O(N) instead of O(N*NB) scanning.
        nb = ctx.nbars
        bar_starts = [ctx.bars.start(m) for m in range(nb)]
        bar_ends = [ctx.bars.end(m) for m in range(nb)]
        indexed_items = {}
        for ev_list in plan.EV.values():
            by_bar = [[] for _ in range(nb)]
            for ev in ev_list:
                on_v, end_v = ev['on'], ev['end']
                m0 = bisect_right(bar_ends, on_v)
                m1 = bisect_left(bar_starts, end_v)
                for m in range(m0, m1):
                    lo_m, hi_m = bar_starts[m], bar_ends[m]
                    s, e = (on_v if on_v > lo_m else lo_m), (end_v if end_v < hi_m else hi_m)
                    by_bar[m].append((s - lo_m, e - lo_m, dict(ev=ev, tie_in=on_v < lo_m, tie_out=end_v > hi_m)))
            ev_id = id(ev_list)
            for m in range(nb):
                indexed_items[(ev_id, bar_starts[m], bar_ends[m])] = by_bar[m]

        def fast_items(events, lo, hi):
            cached = indexed_items.get((id(events), lo, hi))
            if cached is not None:
                return [(s, e, dict(pl)) for s, e, pl in cached]
            return original_items(events, lo, hi)

        baseline = Path(path).with_suffix('.unpolished.musicxml')
        musicxml.layout_voice = original_layout
        musicxml.bar_items = fast_items
        try:
            original_write(plan, ctx, baseline)
            before = sounding_signature(baseline)
        finally:
            musicxml.layout_voice = layout
            baseline.unlink(missing_ok=True)
        mapping = {}
        for staff in (0, 1):
            a, b = plan.EV[(staff, 'A')], plan.EV[(staff, 'B')]
            streams = [(fast_items(a, bar_starts[m], bar_ends[m]),
                        fast_items(b, bar_starts[m], bar_ends[m])) for m in range(nb)]
            for m in sorted(compactable_bars(streams)):
                lo, hi = bar_starts[m], bar_ends[m]
                mapping[(id(a), lo, hi)] = sequential_items(*streams[m])
                mapping[(id(b), lo, hi)] = []
                audit['collapsed_staff_bars'].append({'staff': staff + 1,
                    'measure': m + (0 if ctx.pickup else 1)})
        def items(events, lo, hi):
            key = (id(events), lo, hi)
            return mapping[key] if key in mapping else fast_items(events, lo, hi)
        musicxml.bar_items = items
        try:
            result = original_write(plan, ctx, path)
            audit.update(simplify_release_rests(path))
            audit.update(normalize_tied_spelling(path))
            if sounding_signature(path) != before:
                raise ValueError('Readability cleanup changed musical events')
            audit['sounding_events_preserved'] = True
            return result
        finally:
            musicxml.bar_items = original_items

    upstream.write, musicxml.layout_voice, upstream.assign = write, layout, assign
    musicxml.type_of = type_of
    try:
        yield audit
    finally:
        upstream.write, musicxml.layout_voice = original_write, original_layout
        upstream.assign = original_assign
        musicxml.bar_items = original_items
        musicxml.type_of = original_type
